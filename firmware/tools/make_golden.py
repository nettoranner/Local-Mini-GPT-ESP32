"""Create main/golden_data.h: reference vectors for the firmware's boot self-test.

    python tools/make_golden.py model/model.bin

The expected values come from tools/cmlp.py (a bit-exact Python twin of the C++ code). Run it again
after every model change; the firmware compares the model CRC and refuses to trust stale golden data.
"""
import pathlib
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import cmlp  # noqa: E402

OUT = HERE.parent / "main" / "golden_data.h"


def main():
    path = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else HERE.parent / "model" / "model.bin")
    m, crc = cmlp.load(path)
    L, V = m.ctx_len, m.vocab_in
    rng = np.random.default_rng(2026)
    cases = [rng.integers(0, V, L) for _ in range(3)]
    cases += [np.full(L, 1), np.full(L, V - 2), np.arange(L) % V]
    hid, logits = [], []
    for w in cases:
        h, lg = cmlp.predict(m, w)
        hid.append(h)
        logits.append(lg)

    def arr(name, ctype, rows, fmt):
        out = [f"static const {ctype} {name}[GOLDEN_NUM_CASES][{len(rows[0])}] = {{"]
        out += ["  {" + ", ".join(fmt(v) for v in r) + "}," for r in rows]
        out.append("};")
        return "\n".join(out)

    text = "\n".join([
        "// GENERATED by tools/make_golden.py - do not edit.",
        "#pragma once",
        "#include <cstdint>",
        "#define GOLDEN_VALID 1",
        f"#define GOLDEN_NUM_CASES {len(cases)}",
        f"#define GOLDEN_CTX_LEN {L}",
        f"#define GOLDEN_HIDDEN {m.hidden}",
        f"#define GOLDEN_OUT_VOCAB {m.vocab_out}",
        f"static const uint32_t kGoldenPayloadCrc = 0x{crc:08X}u;",
        arr("kGoldenInput", "uint16_t", cases, lambda v: str(int(v))),
        arr("kGoldenHidden", "int8_t", hid, lambda v: str(int(v))),
        arr("kGoldenLogits", "float", logits, lambda v: repr(float(v)) + "f"),
        "",
    ])
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}: {len(cases)} cases, model CRC {crc:08X}")


if __name__ == "__main__":
    main()
