"""Generate main/vocab.cpp: the table  model index -> text.

The order MUST be the one used in training (the vocab.json written by training/build_qa.py):
    index 0   "\\x00"   padding (left fill of the window, never printed)
    1..95     printable ASCII, space ... '~'
    96        "\\n"      separates the question from the answer
    97        "\\x03"    END of the answer

  python tools/export_vocab.py --builtin                # that exact order (already what is shipped)
  python tools/export_vocab.py --json vocab.json        # take the order from your training vocab.json
  python tools/export_vocab.py --json vocab.json --check  # only compare with the built-in order
"""
import argparse
import json
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "main" / "vocab.cpp"
PAD, END = "\x00", "\x03"
BUILTIN = [PAD] + [chr(c) for c in range(32, 127)] + ["\n", END]


def c_literal(s):
    if s == PAD:
        return '""'          # empty string: index 0 is the padding symbol
    out = []
    for b in s.encode("utf-8"):
        ch = chr(b)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= b < 127 and ch != "?":      # '?' is escaped to avoid trigraphs
            out.append(ch)
        else:
            out.append("\\%03o" % b)           # octal escapes never swallow the next character
    return '"' + "".join(out) + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--builtin", action="store_true")
    g.add_argument("--json")
    ap.add_argument("--check", action="store_true", help="only compare, do not write")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()

    chars = BUILTIN if a.builtin else json.loads(pathlib.Path(a.json).read_text(encoding="utf-8"))
    if a.check:
        if chars == BUILTIN:
            print(f"OK: {len(chars)} symbols, identical to the built-in order")
            return
        for i, (x, y) in enumerate(zip(chars, BUILTIN)):
            if x != y:
                sys.exit(f"DIFFERENT at index {i}: json has {x!r}, built-in has {y!r}")
        sys.exit(f"DIFFERENT length: json {len(chars)}, built-in {len(BUILTIN)}")

    if PAD not in chars or END not in chars or "\n" not in chars:
        sys.exit("vocabulary must contain the padding symbol \\x00, newline and END \\x03")
    if len(set(chars)) != len(chars):
        sys.exit("duplicate symbols in the vocabulary")
    pad_idx, end_idx = chars.index(PAD), chars.index(END)

    lines = ["// GENERATED by tools/export_vocab.py - do not edit.", '#include "vocab.h"', "",
             "const char* const kVocab[] = {"]
    lines += [f"    {c_literal(c)},  // {i}: {c!r}" for i, c in enumerate(chars)]
    lines += ["};", f"const int kVocabSize = {len(chars)};", f"const int kVocabPadIndex = {pad_idx};",
              f"const int kVocabEndIndex = {end_idx};", ""]
    pathlib.Path(a.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {a.out}: {len(chars)} symbols (pad index {pad_idx}, end index {end_idx})")


if __name__ == "__main__":
    main()
